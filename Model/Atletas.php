/**
 * Busca un atleta por su cédula
 * @param string $cedula - Cédula del atleta
 * @param array $lista_atletas - Lista de atletas
 * @return array|null - Retorna el atleta encontrado o null si no existe
 */
function buscarAtletaPorCedula($cedula, $lista_atletas = null) {
    global $todos_los_atletas;
    $atletas = $lista_atletas ?? $todos_los_atletas;
    
    foreach ($atletas as $atleta) {
        if ($atleta['atleta_cedula'] === $cedula) {
            return $atleta;
        }
    }
    return null;
}





/**
 * Busca atletas por categoría
 * @param string $categoria - Categoría del atleta (ej. Sub-12)
 * @param array $lista_atletas - Lista de atletas
 * @return array - Retorna los atletas encontrados
 */
function buscarAtletasPorCategoria($categoria, $lista_atletas = null) {
    global $todos_los_atletas;
    $atletas = $lista_atletas ?? $todos_los_atletas;
    $resultado = [];
    
    foreach ($atletas as $atleta) {
        if ($atleta['atleta_categoria'] === $categoria) {
            $resultado[] = $atleta;
        }
    }
    return $resultado;
}

/**
 * Busca atletas por sexo
 * @param string $sexo - Sexo del atleta (Masculino/Femenino)
 * @param array $lista_atletas - Lista de atletas
 * @return array - Retorna los atletas encontrados
 */
function buscarAtletasPorSexo($sexo, $lista_atletas = null) {
    global $todos_los_atletas;
    $atletas = $lista_atletas ?? $todos_los_atletas;
    $resultado = [];
    
    foreach ($atletas as $atleta) {
        if ($atleta['atleta_sexo'] === $sexo) {
            $resultado[] = $atleta;
        }
    }
    return $resultado;
}

/**
 * Verifica si un atleta ya está registrado
 * @param string $cedula - Cédula del atleta
 * @param string $primer_nombre - Primer nombre del atleta
 * @param string $primer_apellido - Primer apellido del atleta
 * @param array $lista_atletas - Lista de atletas
 * @return bool - Retorna true si ya existe, false si no
 */
function atletaYaExiste($cedula, $primer_nombre, $primer_apellido, $lista_atletas = null) {
    global $todos_los_atletas;
    $atletas = $lista_atletas ?? $todos_los_atletas;
    
    foreach ($atletas as $atleta) {
        if ($atleta['atleta_cedula'] === $cedula || 
            ($atleta['atleta_primer_nombre'] === $primer_nombre && 
             $atleta['atleta_primer_apellido'] === $primer_apellido)) {
            return true;
        }
    }
    return false;
}


/**
 * Agrega un nuevo atleta al sistema
 * @param array $atleta - Array con los datos del atleta
 * @return array - Resultado de la operación
 */
function agregarAtleta($atleta) {
    global $todos_los_atletas;
    
    // Verificar si el atleta ya existe por cédula
    if (buscarAtletaPorCedula($atleta['atleta_cedula']) !== null) {
        return [
            'success' => false,
            'mensaje' => 'El atleta con esta cédula ya existe en el sistema',
            'codigo' => 'DUPLICADO_CEDULA'
        ];
    }
    
    // Verificar si el atleta ya existe por nombre y apellido (opcional)
    foreach ($todos_los_atletas as $at) {
        if ($at['atleta_primer_nombre'] === $atleta['atleta_primer_nombre'] && 
            $at['atleta_primer_apellido'] === $atleta['atleta_primer_apellido'] &&
            $at['atleta_segundo_nombre'] === $atleta['atleta_segundo_nombre'] &&
            $at['atleta_segundo_apellido'] === $atleta['atleta_segundo_apellido']) {
            return [
                'success' => false,
                'mensaje' => 'Ya existe un atleta con este nombre completo',
                'codigo' => 'DUPLICADO_NOMBRE'
            ];
        }
    }
    
    // Agregar el nuevo atleta al array
    $todos_los_atletas[] = $atleta;
    
    // Verificar que se agregó correctamente
    $atleta_agregado = buscarAtletaPorCedula($atleta['atleta_cedula']);
    if ($atleta_agregado) {
        return [
            'success' => true,
            'mensaje' => 'Atleta registrado exitosamente',
            'codigo' => 'REGISTRO_EXITOSO',
            'atleta' => $atleta_agregado,
            'cedula' => $atleta['atleta_cedula'],
            'nombre_completo' => $atleta['atleta_primer_nombre'] . ' ' . 
                                  $atleta['atleta_primer_apellido'],
            'categoria' => $atleta['atleta_categoria'],
            'fecha_registro' => date('Y-m-d H:i:s')
        ];
    } else {
        return [
            'success' => false,
            'mensaje' => 'Error al registrar el atleta',
            'codigo' => 'ERROR_REGISTRO'
        ];
    }
}

/**
 * Actualiza los datos de un atleta existente
 * @param string $cedula - Cédula del atleta a actualizar
 * @param array $nuevos_datos - Array con los nuevos datos
 * @param array $lista_atletas - Lista de atletas (opcional)
 * @return array - Resultado de la operación
 */

function actualizarAtleta($cedula, $nuevos_datos, $lista_atletas = null) {
    global $todos_los_atletas;
    $atletas = $lista_atletas ?? $todos_los_atletas;
    
    // Buscar el atleta por cédula
    $indice = -1;
    foreach ($atletas as $key => $atleta) {
        if ($atleta['atleta_cedula'] === $cedula) {
            $indice = $key;
            break;
        }
    }
    
    if ($indice === -1) {
        return [
            'success' => false,
            'mensaje' => 'Atleta no encontrado',
            'codigo' => 'NO_ENCONTRADO'
        ];
    }
    
    // Verificar que la cédula no esté siendo cambiada a una que ya existe
    if (isset($nuevos_datos['atleta_cedula']) && 
        $nuevos_datos['atleta_cedula'] !== $cedula) {
        $atleta_existente = buscarAtletaPorCedula($nuevos_datos['atleta_cedula'], $atletas);
        if ($atleta_existente !== null) {
            return [
                'success' => false,
                'mensaje' => 'Ya existe un atleta con la nueva cédula ingresada',
                'codigo' => 'DUPLICADO_CEDULA'
            ];
        }
    }
    
    // Obtener el atleta actual para mantener campos no enviados
    $atleta_actual = $atletas[$indice];
    
    // Fusionar los datos actuales con los nuevos
    $atleta_actualizado = array_merge($atleta_actual, $nuevos_datos);
    
    // Asegurar que la cédula se mantenga (si no se envió en nuevos datos)
    if (!isset($nuevos_datos['atleta_cedula'])) {
        $atleta_actualizado['atleta_cedula'] = $cedula;
    }
    
    // Actualizar el atleta en el array
    $atletas[$indice] = $atleta_actualizado;
    
    // Actualizar la variable global
    $GLOBALS['todos_los_atletas'] = $atletas;
    
    return [
        'success' => true,
        'mensaje' => 'Atleta actualizado exitosamente',
        'codigo' => 'ACTUALIZADO',
        'atleta' => $atleta_actualizado,
        'cedula' => $atleta_actualizado['atleta_cedula'],
        'nombre_completo' => $atleta_actualizado['atleta_primer_nombre'] . ' ' . 
                             $atleta_actualizado['atleta_primer_apellido']
    ];
}

