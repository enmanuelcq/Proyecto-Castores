/**
 * Obtener todas las pruebas de definición
 */
function obtenerTodasDefinicion($pruebas) {
    return $pruebas;
}

/**
 * Buscar prueba de definición por ID
 */
function buscarDefinicionPorId($id, $pruebas) {
    foreach ($pruebas as $p) {
        if ($p['id_definicion'] == $id) {
            return $p;
        }
    }
    return null;
}

/**
 * Buscar pruebas de definición por fecha
 */
function buscarDefinicionPorFecha($fecha, $pruebas) {
    $resultado = [];
    foreach ($pruebas as $p) {
        if ($p['fecha'] == $fecha) {
            $resultado[] = $p;
        }
    }
    return $resultado;
}

/**
 * Obtener pruebas de definición por atleta
 */
function obtenerDefinicionPorAtleta($cedula_atleta, $pruebas) {
    $resultado = [];
    foreach ($pruebas as $p) {
        if ($p['atleta_cedula'] == $cedula_atleta) {
            $resultado[] = $p;
        }
    }
    return $resultado;
}

/**
 * Obtener pruebas de definición por categoría
 */
function obtenerDefinicionPorCategoria($categoria_id, $pruebas) {
    $resultado = [];
    foreach ($pruebas as $p) {
        if ($p['categoria_id'] == $categoria_id) {
            $resultado[] = $p;
        }
    }
    return $resultado;
}

/**
 * Contar pruebas de definición por atleta
 */
function contarDefinicionPorAtleta($cedula_atleta, $pruebas) {
    return count(obtenerDefinicionPorAtleta($cedula_atleta, $pruebas));
}

/**
 * Calcular goles totales de una prueba
 */
function calcularGolesDefinicion($prueba) {
    return $prueba['centro_bajo'] + $prueba['centro_alto'] + 
           $prueba['derecha_bajo'] + $prueba['derecha_alto'] + 
           $prueba['izquierda_bajo'] + $prueba['izquierda_alto'];
}

/**
 * Calcular efectividad de definición por atleta
 */
function efectividadDefinicion($cedula_atleta, $pruebas) {
    $pruebas_atleta = obtenerDefinicionPorAtleta($cedula_atleta, $pruebas);
    if (empty($pruebas_atleta)) return 0;
    
    $total_tiros = 0;
    $total_goles = 0;
    
    foreach ($pruebas_atleta as $p) {
        $total_tiros += $p['cantidad_tiros'];
        $total_goles += calcularGolesDefinicion($p);
    }
    
    return $total_tiros > 0 ? round(($total_goles / $total_tiros) * 100, 2) : 0;
}

/**
 * Calcular distribución de goles por zona
 */
function distribucionGolesDefinicion($cedula_atleta, $pruebas) {
    $pruebas_atleta = obtenerDefinicionPorAtleta($cedula_atleta, $pruebas);
    if (empty($pruebas_atleta)) {
        return [
            'centro_bajo' => 0, 'centro_alto' => 0,
            'derecha_bajo' => 0, 'derecha_alto' => 0,
            'izquierda_bajo' => 0, 'izquierda_alto' => 0
        ];
    }
    
    $distribucion = [
        'centro_bajo' => 0, 'centro_alto' => 0,
        'derecha_bajo' => 0, 'derecha_alto' => 0,
        'izquierda_bajo' => 0, 'izquierda_alto' => 0
    ];
    
    foreach ($pruebas_atleta as $p) {
        $distribucion['centro_bajo'] += $p['centro_bajo'];
        $distribucion['centro_alto'] += $p['centro_alto'];
        $distribucion['derecha_bajo'] += $p['derecha_bajo'];
        $distribucion['derecha_alto'] += $p['derecha_alto'];
        $distribucion['izquierda_bajo'] += $p['izquierda_bajo'];
        $distribucion['izquierda_alto'] += $p['izquierda_alto'];
    }
    
    return $distribucion;
}

/**
 * Obtener mejor registro de definición por atleta
 */
function mejorDefinicionPorAtleta($cedula_atleta, $pruebas) {
    $pruebas_atleta = obtenerDefinicionPorAtleta($cedula_atleta, $pruebas);
    if (empty($pruebas_atleta)) return null;
    
    $mejor = $pruebas_atleta[0];
    $mejor_efectividad = efectividadDefinicionPrueba($pruebas_atleta[0]);
    
    foreach ($pruebas_atleta as $p) {
        $efectividad = efectividadDefinicionPrueba($p);
        if ($efectividad > $mejor_efectividad) {
            $mejor = $p;
            $mejor_efectividad = $efectividad;
        }
    }
    return $mejor;
}

/**
 * Calcular efectividad de una prueba individual
 */
function efectividadDefinicionPrueba($prueba) {
    $goles = calcularGolesDefinicion($prueba);
    return $prueba['cantidad_tiros'] > 0 ? round(($goles / $prueba['cantidad_tiros']) * 100, 2) : 0;
}

/**
 * Obtener último registro de definición por atleta
 */
function ultimoDefinicionPorAtleta($cedula_atleta, $pruebas) {
    $pruebas_atleta = obtenerDefinicionPorAtleta($cedula_atleta, $pruebas);
    if (empty($pruebas_atleta)) return null;
    
    usort($pruebas_atleta, function($a, $b) {
        return strtotime($b['fecha']) - strtotime($a['fecha']);
    });
    return $pruebas_atleta[0];
}

/**
 * Obtener estadísticas generales de definición
 */
function estadisticasGeneralesDefinicion($pruebas) {
    if (empty($pruebas)) {
        return [
            'total_pruebas' => 0,
            'total_tiros' => 0,
            'total_goles' => 0,
            'efectividad_promedio' => 0,
            'total_atletas' => 0
        ];
    }
    
    $total_tiros = 0;
    $total_goles = 0;
    $atletas = [];
    
    foreach ($pruebas as $p) {
        $total_tiros += $p['cantidad_tiros'];
        $total_goles += calcularGolesDefinicion($p);
        $atletas[] = $p['atleta_cedula'];
    }
    
    return [
        'total_pruebas' => count($pruebas),
        'total_tiros' => $total_tiros,
        'total_goles' => $total_goles,
        'efectividad_promedio' => $total_tiros > 0 ? round(($total_goles / $total_tiros) * 100, 2) : 0,
        'total_atletas' => count(array_unique($atletas))
    ];
}

/**
 * Filtrar pruebas de definición por criterios
 */
function filtrarDefinicion($pruebas, $filtros = []) {
    $resultado = $pruebas;
    
    if (isset($filtros['atleta_cedula'])) {
        $resultado = array_filter($resultado, function($p) use ($filtros) {
            return $p['atleta_cedula'] == $filtros['atleta_cedula'];
        });
    }
    
    if (isset($filtros['categoria_id'])) {
        $resultado = array_filter($resultado, function($p) use ($filtros) {
            return $p['categoria_id'] == $filtros['categoria_id'];
        });
    }
    
    if (isset($filtros['efectividad_min'])) {
        $resultado = array_filter($resultado, function($p) use ($filtros) {
            return efectividadDefinicionPrueba($p) >= $filtros['efectividad_min'];
        });
    }
    
    return array_values($resultado);
}

/**
 * Obtener resumen rápido de definición para un atleta
 */
function resumenDefinicionAtleta($cedula_atleta, $pruebas) {
    $pruebas_atleta = obtenerDefinicionPorAtleta($cedula_atleta, $pruebas);
    $ultima = ultimoDefinicionPorAtleta($cedula_atleta, $pruebas);
    $mejor = mejorDefinicionPorAtleta($cedula_atleta, $pruebas);
    
    return [
        'total_pruebas' => count($pruebas_atleta),
        'efectividad_promedio' => efectividadDefinicion($cedula_atleta, $pruebas),
        'mejor_efectividad' => $mejor ? efectividadDefinicionPrueba($mejor) : 0,
        'distribucion_goles' => distribucionGolesDefinicion($cedula_atleta, $pruebas),
        'ultima_fecha' => $ultima ? $ultima['fecha'] : null,
        'ultima_efectividad' => $ultima ? efectividadDefinicionPrueba($ultima) : 0
    ];
}
