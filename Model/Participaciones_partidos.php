/**
 * Obtener participaciones de un atleta
 */
function obtenerParticipacionesPorAtleta($cedula_atleta, $todas_las_participaciones) {
    $resultado = [];
    foreach ($todas_las_participaciones as $p) {
        if ($p['atleta_cedula'] == $cedula_atleta) {
            $resultado[] = $p;
        }
    }
    return $resultado;
}

/**
 * Obtener participaciones de un partido
 */
function obtenerParticipacionesPorPartido($partido_id, $todas_las_participaciones) {
    $resultado = [];
    foreach ($todas_las_participaciones as $p) {
        if ($p['partido_id'] == $partido_id) {
            $resultado[] = $p;
        }
    }
    return $resultado;
}

/**
 * Calcular total de goles de un atleta
 */
function calcularGolesAtleta($cedula_atleta, $todas_las_participaciones) {
    $participaciones = obtenerParticipacionesPorAtleta($cedula_atleta, $todas_las_participaciones);
    $total = 0;
    foreach ($participaciones as $p) {
        $total += $p['goles'];
    }
    return $total;
}

/**
 * Calcular total de asistencias de un atleta
 */
function calcularAsistenciasAtleta($cedula_atleta, $todas_las_participaciones) {
    $participaciones = obtenerParticipacionesPorAtleta($cedula_atleta, $todas_las_participaciones);
    $total = 0;
    foreach ($participaciones as $p) {
        $total += $p['asistencias'];
    }
    return $total;
}

/**
 * Calcular total de minutos jugados por un atleta
 */
function calcularMinutosAtleta($cedula_atleta, $todas_las_participaciones) {
    $participaciones = obtenerParticipacionesPorAtleta($cedula_atleta, $todas_las_participaciones);
    $total = 0;
    foreach ($participaciones as $p) {
        $total += $p['minutos_jugados'];
    }
    return $total;
}

/**
 * Calcular tarjetas de un atleta
 */
function calcularTarjetasAtleta($cedula_atleta, $todas_las_participaciones) {
    $participaciones = obtenerParticipacionesPorAtleta($cedula_atleta, $todas_las_participaciones);
    $amarillas = 0;
    $rojas = 0;
    foreach ($participaciones as $p) {
        $amarillas += $p['tarjetas_amarillas'];
        $rojas += $p['tarjetas_rojas'];
    }
    return [
        'amarillas' => $amarillas,
        'rojas' => $rojas
    ];
}

/**
 * Calcular promedio de calificación de un atleta
 */
function calcularPromedioCalificacionAtleta($cedula_atleta, $todas_las_participaciones) {
    $participaciones = obtenerParticipacionesPorAtleta($cedula_atleta, $todas_las_participaciones);
    if (empty($participaciones)) return 0;
    $total = 0;
    foreach ($participaciones as $p) {
        $total += $p['calificacion'];
    }
    return round($total / count($participaciones), 2);
}

/**
 * Obtener resumen de partidos de un atleta
 */
function resumenPartidosAtleta($cedula_atleta, $todas_las_participaciones, $todos_los_partidos) {
    $participaciones = obtenerParticipacionesPorAtleta($cedula_atleta, $todas_las_participaciones);
    
    $resumen = [
        'total_partidos' => count($participaciones),
        'goles' => calcularGolesAtleta($cedula_atleta, $todas_las_participaciones),
        'asistencias' => calcularAsistenciasAtleta($cedula_atleta, $todas_las_participaciones),
        'minutos' => calcularMinutosAtleta($cedula_atleta, $todas_las_participaciones),
        'tarjetas' => calcularTarjetasAtleta($cedula_atleta, $todas_las_participaciones),
        'promedio_calificacion' => calcularPromedioCalificacionAtleta($cedula_atleta, $todas_las_participaciones),
        'partidos' => []
    ];
    
    // Obtener detalles de cada partido
    foreach ($participaciones as $p) {
        // Buscar el partido
        $partido = null;
        foreach ($todos_los_partidos as $part) {
            if ($part['id'] == $p['partido_id']) {
                $partido = $part;
                break;
            }
        }
        
        if ($partido) {
            $resumen['partidos'][] = [
                'partido' => $partido,
                'participacion' => $p
            ];
        }
    }
    
    // Ordenar partidos por fecha (más reciente primero)
    usort($resumen['partidos'], function($a, $b) {
        return strtotime($b['partido']['fecha']) - strtotime($a['partido']['fecha']);
    });
    
    return $resumen;
}

/**
 * Obtener goleadores de un partido
 */
function obtenerGoleadoresPartido($partido_id, $todas_las_participaciones, $todos_los_atletas) {
    $participaciones = obtenerParticipacionesPorPartido($partido_id, $todas_las_participaciones);
    $goleadores = [];
    
    foreach ($participaciones as $p) {
        if ($p['goles'] > 0) {
            // Buscar nombre del atleta
            $nombre = $p['atleta_cedula'];
            foreach ($todos_los_atletas as $a) {
                if ($a['atleta_cedula'] == $p['atleta_cedula']) {
                    $nombre = $a['atleta_primer_nombre'] . ' ' . $a['atleta_primer_apellido'];
                    break;
                }
            }
            $goleadores[] = [
                'atleta_cedula' => $p['atleta_cedula'],
                'nombre' => $nombre,
                'goles' => $p['goles']
            ];
        }
    }
    
    // Ordenar por goles (mayor a menor)
    usort($goleadores, function($a, $b) {
        return $b['goles'] - $a['goles'];
    });
    
    return $goleadores;
}

/**
 * Obtener estadísticas de un partido
 */
function obtenerEstadisticasPartido($partido_id, $todas_las_participaciones) {
    $participaciones = obtenerParticipacionesPorPartido($partido_id, $todas_las_participaciones);
    
    $total_goles = 0;
    $total_asistencias = 0;
    $total_amarillas = 0;
    $total_rojas = 0;
    $total_minutos = 0;
    
    foreach ($participaciones as $p) {
        $total_goles += $p['goles'];
        $total_asistencias += $p['asistencias'];
        $total_amarillas += $p['tarjetas_amarillas'];
        $total_rojas += $p['tarjetas_rojas'];
        $total_minutos += $p['minutos_jugados'];
    }
    
    return [
        'total_jugadores' => count($participaciones),
        'total_goles' => $total_goles,
        'total_asistencias' => $total_asistencias,
        'total_amarillas' => $total_amarillas,
        'total_rojas' => $total_rojas,
        'promedio_minutos' => count($participaciones) > 0 ? round($total_minutos / count($participaciones), 0) : 0
    ];
}

/**
 * Obtener mejores jugadores del torneo (por goles)
 */
function obtenerMaximosGoleadores($todas_las_participaciones, $todos_los_atletas, $limite = 5) {
    $goleadores = [];
    
    // Agrupar goles por atleta
    foreach ($todas_las_participaciones as $p) {
        $cedula = $p['atleta_cedula'];
        if (!isset($goleadores[$cedula])) {
            $goleadores[$cedula] = 0;
        }
        $goleadores[$cedula] += $p['goles'];
    }
    
    // Filtrar los que tienen goles > 0
    $goleadores = array_filter($goleadores, function($goles) {
        return $goles > 0;
    });
    
    // Ordenar de mayor a menor
    arsort($goleadores);
    
    // Tomar los primeros $limite
    $goleadores = array_slice($goleadores, 0, $limite, true);
    
    // Agregar nombres
    $resultado = [];
    foreach ($goleadores as $cedula => $goles) {
        $nombre = $cedula;
        foreach ($todos_los_atletas as $a) {
            if ($a['atleta_cedula'] == $cedula) {
                $nombre = $a['atleta_primer_nombre'] . ' ' . $a['atleta_primer_apellido'];
                break;
            }
        }
        $resultado[] = [
            'atleta_cedula' => $cedula,
            'nombre' => $nombre,
            'goles' => $goles
        ];
    }
    
    return $resultado;
}
