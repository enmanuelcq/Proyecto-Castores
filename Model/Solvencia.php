/**
 * Obtiene los meses que ya han pasado o el mes actual
 * @return array Array con los nombres de los meses activos en minúscula
 */
function obtenerMesesActivos() {
    $meses = ['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre'];
    $mes_actual = intval(date('n')) - 1; // 0 = enero, 1 = febrero, etc.
    
    // Devolver solo los meses desde enero hasta el mes actual
    return array_slice($meses, 0, $mes_actual + 1);
}

/**
 * Obtiene el mes actual en texto
 */
function obtenerMesActualTexto() {
    $meses = ['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre'];
    return $meses[intval(date('n')) - 1];
}

/**
 * Verifica si un mes es futuro (no ha llegado aún)
 */
function esMesFuturo($nombre_mes) {
    $meses_activos = obtenerMesesActivos();
    return !in_array($nombre_mes, $meses_activos);
}

/**
 * Obtiene el nombre del mes en español con primera letra mayúscula
 */
function obtenerNombreMes($mes) {
    $meses = [
        'enero' => 'Enero',
        'febrero' => 'Febrero',
        'marzo' => 'Marzo',
        'abril' => 'Abril',
        'mayo' => 'Mayo',
        'junio' => 'Junio',
        'julio' => 'Julio',
        'agosto' => 'Agosto',
        'septiembre' => 'Septiembre',
        'octubre' => 'Octubre',
        'noviembre' => 'Noviembre',
        'diciembre' => 'Diciembre'
    ];
    return $meses[$mes] ?? ucfirst($mes);
}
